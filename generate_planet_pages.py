def build_paragraphs(texts):
    return '\n'.join(f'                <p class="section-text">{t}</p>' for t in texts)


def build_comp_bars(bars):
    lines = []
    for label, pct, color in bars:
        lines.append(f'''\
                    <div class="comp-bar-row">
                        <span class="comp-bar-label">{label}</span>
                        <div class="comp-bar-track">
                            <div class="comp-bar-fill" style="background:{color};width:{pct}%"></div>
                        </div>
                        <span class="comp-bar-pct">{pct}%</span>
                    </div>''')
    return '\n'.join(lines)


